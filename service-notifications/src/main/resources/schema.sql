CREATE TABLE IF NOT EXISTS notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id BIGINT NOT NULL,
    invoice_id BIGINT NOT NULL,
    type VARCHAR(24) NOT NULL,
    recipient_email VARCHAR(255),
    subject VARCHAR(255) NOT NULL,
    message TEXT NOT NULL,
    status VARCHAR(24) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    next_attempt_at TIMESTAMP WITH TIME ZONE NOT NULL,
    delivery_started_at TIMESTAMP WITH TIME ZONE,
    sent_at TIMESTAMP WITH TIME ZONE,
    last_failure VARCHAR(40),
    CONSTRAINT uk_notification_invoice_type UNIQUE (invoice_id, type)
);

CREATE INDEX IF NOT EXISTS ix_notifications_client ON notifications (client_id);
CREATE INDEX IF NOT EXISTS ix_notifications_due ON notifications (status, delivery_started_at, next_attempt_at);
